"use client";

import { Bell, RefreshCw, ShieldAlert } from "lucide-react";
import { useMemo, useState } from "react";
import { Card, PageHeader, SeverityBadge } from "@/components/ui";
import { api } from "@/lib/api";
import { useApi } from "@/lib/useApi";
import type { AlertItem } from "@/lib/types";

function formatDateTime(value: string | Date) {
  return new Date(value).toLocaleString();
}

export default function AlertsPage() {
  const { data, error, loading, reload } =
    useApi<{ items: AlertItem[] }>("/api/alerts");

  const [severity, setSeverity] = useState("all");
  const [attackType, setAttackType] = useState("all");
  const [selected, setSelected] = useState<AlertItem | null>(null);

  const alerts = data?.items ?? [];

  const attackTypes = useMemo(
    () => Array.from(new Set(alerts.map((a) => a.attackType))).sort(),
    [alerts],
  );

  const filtered = alerts.filter((a) => {
    if (severity !== "all" && a.severity.toLowerCase() !== severity) return false;
    if (attackType !== "all" && a.attackType !== attackType) return false;
    return true;
  });

  async function clearAll() {
    if (!confirm("Clear all stored alerts?")) return;

    try {
      await api("/api/alerts", { method: "DELETE" });
      setSelected(null);
      reload();
    } catch (e) {
      alert(e instanceof Error ? e.message : "Could not clear alerts");
    }
  }

  return (
    <>
      <PageHeader
        title="Alert Center"
        description="Review persisted security alerts generated by the scan and network-analysis APIs."
        actions={
          <>
            <button className="btn" onClick={reload} disabled={loading}>
              <RefreshCw
                size={15}
                className={loading ? "animate-spin" : ""}
              />
              Refresh
            </button>

            <button
              className="btn btn-danger"
              onClick={clearAll}
              disabled={!alerts.length}
            >
              Clear all
            </button>
          </>
        }
      />

      <div className="mb-4 flex flex-wrap gap-2">
        {["all", "critical", "high", "medium", "low"].map((s) => (
          <button
            key={s}
            className={severity === s ? "btn btn-primary" : "btn"}
            onClick={() => setSeverity(s)}
          >
            {s === "all" ? "All severities" : s}
          </button>
        ))}

        <select
          className="input min-w-44"
          value={attackType}
          onChange={(e) => setAttackType(e.target.value)}
        >
          <option value="all">All attack types</option>
          {attackTypes.map((type) => (
            <option key={type} value={type}>
              {type}
            </option>
          ))}
        </select>
      </div>

      {error && (
        <p className="mb-4 rounded-lg border border-red-500/40 bg-red-500/10 px-3 py-2 text-sm text-red-300">
          {error}
        </p>
      )}

      <div className="grid gap-4 lg:grid-cols-[1fr_360px]">
        <Card
          title={`${filtered.length} alerts`}
          subtitle="Newest alerts appear first"
        >
          <div className="space-y-2">
            {filtered.map((alert) => (
              <button
                key={alert.id}
                onClick={() => setSelected(alert)}
                className={`w-full rounded-lg border p-3 text-left transition ${
                  selected?.id === alert.id
                    ? "border-emerald-500/50 bg-emerald-500/5"
                    : "border-soc-line bg-soc-bg/40 hover:border-soc-line/80"
                }`}
              >
                <div className="flex items-center gap-2">
                  <ShieldAlert size={16} className="text-red-400" />

                  <span className="font-semibold text-slate-100">
                    {alert.title}
                  </span>

                  <SeverityBadge severity={alert.severity} />
                </div>

                <p className="mt-1 text-xs text-soc-muted">
                  {formatDateTime(alert.createdAt)}
                </p>

                {alert.description && (
                  <p className="mt-2 line-clamp-2 text-sm text-slate-300">
                    {alert.description}
                  </p>
                )}
              </button>
            ))}

            {!loading && filtered.length === 0 && (
              <div className="py-12 text-center">
                <Bell
                  className="mx-auto mb-2 text-soc-muted"
                  size={24}
                />
                <p className="text-sm text-slate-300">
                  No alerts match the current filters.
                </p>
              </div>
            )}
          </div>
        </Card>

        <Card
          title="Alert details"
          subtitle="Select an alert to inspect it"
        >
          {selected ? (
            <div className="space-y-4 text-sm">
              <div className="flex items-center justify-between">
                <span className="text-soc-muted">Severity</span>
                <SeverityBadge severity={selected.severity} />
              </div>

              <div className="flex items-center justify-between">
                <span className="text-soc-muted">Attack</span>
                <span className="font-medium text-white">
                  {selected.attackType}
                </span>
              </div>

              <div className="flex items-center justify-between">
                <span className="text-soc-muted">Status</span>
                <span className="font-medium text-slate-200">
                  {selected.status}
                </span>
              </div>

              <div className="flex items-center justify-between">
                <span className="text-soc-muted">Source</span>
                <span className="font-medium text-slate-200">
                  {selected.source}
                </span>
              </div>

              <div className="flex items-center justify-between">
                <span className="text-soc-muted">Confidence</span>
                <span className="font-mono text-xs text-slate-200">
                  {(selected.confidence * 100).toFixed(1)}%
                </span>
              </div>

              <div>
                <p className="text-soc-muted">Description</p>
                <p className="mt-1 text-slate-200">
                  {selected.description || "No description provided."}
                </p>
              </div>

              <div>
                <p className="text-soc-muted">Recommended action</p>
                <p className="mt-1 text-slate-200">
                  {selected.recommendedAction}
                </p>
              </div>

              <div>
                <p className="text-soc-muted">Created</p>
                <p className="mt-1 font-mono text-xs text-slate-300">
                  {formatDateTime(selected.createdAt)}
                </p>
              </div>
            </div>
          ) : (
            <p className="text-sm text-soc-muted">
              Choose an alert from the list.
            </p>
          )}
        </Card>
      </div>
    </>
  );
}
